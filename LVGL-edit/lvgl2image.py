WIDTH = 50
HEIGHT = 26
PALETTE_SIZE = 8  # 先頭8バイトがパレット
PREFIX = "mentako_check"
BYTES_PER_ROW = (WIDTH + 7) // 8  # 50→7バイト

for idx, data in enumerate(data_list):
    img = Image.new("1", (WIDTH, HEIGHT), 1)
    bitmap = data[PALETTE_SIZE:]  # パレットをスキップ

    for y in range(HEIGHT):
        for x in range(WIDTH):
            byte_index = y * BYTES_PER_ROW + (x // 8)
            bit_index = 7 - (x % 8)
            if (bitmap[byte_index] >> bit_index) & 1:
                img.putpixel((x, y), 0)
            else:
                img.putpixel((x, y), 1)

    filename = f"{PREFIX}_{idx}.bmp"
    img.save(filename)
    print(f"{filename} を保存しました")